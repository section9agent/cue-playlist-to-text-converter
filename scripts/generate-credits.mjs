#!/usr/bin/env node
// Writes src/credits.js: every Rust library the app is built from, with its license and a link.
// The list comes straight from the dependency lock file, so it cannot drift from what ships.
// Needs Rust (cargo). Run it with: npm run credits
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = join(root, 'src-tauri', 'Cargo.toml');

const raw = execFileSync('cargo', ['metadata', '--format-version', '1', '--manifest-path', manifest], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 1024 * 1024 * 1024
});
const meta = JSON.parse(raw);
const own = new Set(meta.workspace_members);

const seen = new Set();
const crates = [];
for (const p of meta.packages) {
  if (own.has(p.id)) continue;
  const key = `${p.name}@${p.version}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const link = [p.repository, p.homepage].find((u) => typeof u === 'string' && u.startsWith('https://'));
  crates.push({
    name: p.name,
    version: p.version,
    license: p.license || (p.license_file ? 'see license file in the project' : 'not stated'),
    url: link || `https://crates.io/crates/${p.name}`
  });
}
crates.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

const lines = crates.map((c) => '    ' + JSON.stringify(c));
const out =
  '// Generated by scripts/generate-credits.mjs. Do not edit by hand.\n' +
  'window.CREDITS = {\n' +
  `  "count": ${crates.length},\n` +
  '  "crates": [\n' + lines.join(',\n') + '\n  ]\n' +
  '};\n';
writeFileSync(join(root, 'src', 'credits.js'), out);
console.log(`Wrote src/credits.js with ${crates.length} libraries.`);
